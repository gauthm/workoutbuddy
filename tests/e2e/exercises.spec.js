import {test,expect} from './fixtures.js'
import {L,get,homeGym,pending,planned,trainThroughUI} from './helpers.js'
import {readFileSync} from 'node:fs'
const en=JSON.parse(readFileSync(new URL('../../public/locales/en.json',import.meta.url),'utf8'))
async function language(page,lang){
 await page.goto('/#/settings')
 const heading=lang==='en'?L('settings.section_general'):en['settings.section_general']
 await page.getByText(heading,{exact:true}).click()
 await page.locator('#SettingsView-state-settings-language').selectOption(lang)
 const bar=page.getByRole('region',{name:lang==='en'?L('settings.pending_changes'):en['settings.pending_changes'],exact:true})
 await bar.getByRole('button',{name:lang==='en'?L('common.save'):en['common.save'],exact:true}).click()
 await expect(bar).toHaveCount(0)
 await expect(pending(page)).toHaveCount(0)
 await expect(page.locator('html')).toHaveAttribute('lang',lang)
}
test('search and filters preserved after returning from details, catalog-only and equipment constraints respected',async({page,request})=>{
 await homeGym(request)
 await page.goto('/#/exercises')
 await page.getByRole('searchbox',{name:L('exercises.search'),exact:true}).fill('haltères')
 await page.locator('.exercise-filter__panel > summary').click()
 await page.getByRole('combobox',{name:L('exercises.filter_muscle'),exact:true}).selectOption('chest')
 await page.getByLabel(L('exercises.available_equipment'),{exact:true}).check()
 await expect(page.locator('.exercise-card').first()).toContainText(/haltères/i)
 const first=await page.locator('.exercise-card__name').first().textContent()
 await page.locator('.exercise-card').first().click()
 await page.waitForURL(/#\/exercises\/[^/]+$/)
 await page.goBack()
 await expect(page.getByRole('searchbox',{name:L('exercises.search'),exact:true})).toHaveValue('haltères')
 await expect(page.getByRole('combobox',{name:L('exercises.filter_muscle'),exact:true})).toHaveValue('chest')
 await expect(page.getByLabel(L('exercises.available_equipment'),{exact:true})).toBeChecked()
 await expect(page.locator('.exercise-card__name').first()).toHaveText(first)
 expect((await get(request,'/exercises')).exercises.every(e=>!e.is_custom)).toBe(true)
})

test('French and English translations: search, instructions, help and language preserved after restart',async({page,request,app})=>{
 const ex=await get(request,'/exercises/dumbbell_bench_press')
 await page.goto('/#/exercises/dumbbell_bench_press')
 await expect(page.getByRole('heading',{name:'Développé couché avec haltères',exact:true})).toBeVisible()
 await expect(page.locator('.instruction-list li').first()).toHaveText(ex.instructions_fr[0])
 await expect(page.locator('.instruction-list li').last()).toHaveText(L('exercises.dumbbell_weight_entry'))
 await language(page,'en')
 await page.goto('/#/exercises/dumbbell_bench_press')
 await expect(page.getByRole('heading',{name:ex.name_en,exact:true})).toBeVisible()
 await expect(page.locator('.instruction-list li').first()).toHaveText(ex.instructions_en[0])
 await expect(page.locator('.instruction-list li').last()).toHaveText(en['exercises.dumbbell_weight_entry'])
 await page.goto('/#/exercises')
 const search=page.getByRole('searchbox',{name:en['exercises.search'],exact:true})
 await search.fill('DEVELOPPE COUCHE AVEC HALTERES')
 await expect(page.locator('.exercise-card__name').filter({hasText:/^Dumbbell Bench Press$/})).toBeVisible()
 await search.fill('Dumbbell Bench Press')
 await expect(page.locator('.exercise-card__name').filter({hasText:/^Dumbbell Bench Press$/})).toBeVisible()
 await app.restart();await page.reload()
 await expect(page.locator('html')).toHaveAttribute('lang','en')
 await page.goto('/#/exercises/dumbbell_bench_press')
 await expect(page.locator('.instruction-list li').first()).toHaveText(ex.instructions_en[0])
 await expect(page.locator('.instruction-list li').last()).toHaveText(en['exercises.dumbbell_weight_entry'])
 await language(page,'fr')
 await page.goto('/#/exercises/dumbbell_bench_press')
 await expect(page.getByRole('heading',{name:ex.name_fr,exact:true})).toBeVisible()
 await expect(page.locator('.instruction-list li').first()).toHaveText(ex.instructions_fr[0])
 await expect(page.locator('.instruction-list li').last()).toHaveText(L('exercises.dumbbell_weight_entry'))
})

test('language changes translate program, workout and record names without altering performance',async({page,request})=>{
 const p=await planned(request)
 const completed=await trainThroughUI(page,request,p)
 const ex=completed.exercises.find(ex=>ex.name_fr!==ex.name_en)
 expect(ex).toBeTruthy()
 const before=await get(request,`/sessions/${completed.id}`)
 await language(page,'en')
 await page.goto(`/#/programs/${p.id}`)
 await expect(page.getByText(ex.name_en+' —',{exact:false}).first()).toBeVisible()
 await page.goto(`/#/session/${completed.id}`)
 await expect(page.getByText(ex.name_en,{exact:true})).toBeVisible()
 await page.goto('/#/stats')
 const records=(await get(request,'/stats/personal-records')).records
 expect(records.length).toBeGreaterThan(0)
 await expect(page.locator('.pr-row__name').first()).toHaveText(records[0].exercise_name_en)
 await page.goto(`/#/programs/${p.id}`)
 await page.getByRole('button',{name:en['programs.start_session'],exact:true}).click()
 await expect(page.locator('.exercise-block').first()).toBeVisible()
 const current=(await get(request,'/sessions?status=in_progress')).sessions[0]
 const active=await get(request,`/sessions/${current.id}`)
 const first=active.exercises[0],detail=await get(request,`/exercises/${first.exercise_id}`)
 await expect(page.locator('.exercise-block__name').first()).toHaveText(first.name_en)
 await page.locator('.exercise-block').first().getByRole('button',{name:en['session.help'],exact:true}).click()
 const help=page.getByRole('dialog',{name:first.name_en,exact:true})
 await expect(help.locator('ol li').first()).toHaveText(detail.instructions_en[0])
 await help.getByRole('button',{name:en['common.close'],exact:true}).click()
 const row=page.locator('.exercise-block').first().locator('.set-row:not(.set-row--warmup)').first()
 await row.locator('input').nth(0).fill('10')
 await row.locator('input').nth(1).fill('8')
 await row.getByRole('button',{name:en['session.validate_set'].replace('{{n}}','1'),exact:true}).click()
 await expect(page.locator('.session-rest-dock__heading span')).toHaveText(first.name_en)
 await page.evaluate(async()=>{const {i18n}=await import('/js/i18n.js');await i18n.setLocale('fr')})
 await expect(page.locator('.session-rest-dock__heading span')).toHaveText(first.name_fr)
 await page.evaluate(async()=>{const {i18n}=await import('/js/i18n.js');await i18n.setLocale('en')})
 await page.goto(`/#/stats/exercise/${ex.exercise_id}`)
 await expect(page.getByRole('heading',{name:ex.name_en,exact:true})).toBeVisible()
 const after=await get(request,`/sessions/${completed.id}`)
 expect(after).toEqual(before)
 // The same mounted component follows the locale without reloading its data.
 await page.evaluate(async()=>{const {i18n}=await import('/js/i18n.js');await i18n.setLocale('fr')})
 await expect(page.getByRole('heading',{name:ex.name_fr,exact:true})).toBeVisible()
})
test('excluding an exercise persists after reload and updates the counter',async({page,request})=>{
 await page.goto('/#/exercises')
 const available=(await get(request,'/exercises?excluded=0')).exercises.length
 const badge=page.locator('.exercise-tabs__badge')
 await expect(badge).toHaveText(String(available))
 const initial=available
 const name=await page.locator('.exercise-card__name').first().textContent()
 await page.locator('.exercise-card').first().getByRole('button',{name:L('exercises.exclude_btn'),exact:true}).click()
 await expect(badge).toHaveText(String(initial-1))
 await page.reload()
 await expect(badge).toHaveText(String(initial-1))
 expect((await get(request,'/exercises?excluded=1')).exercises.some(e=>e.name_fr===name)).toBe(true)
})

 test('load instructions for every dumbbell exercise, without additions for other equipment',async({page,request})=>{
  const catalog=(await get(request,'/exercises')).exercises
  await page.goto('/#/exercises/dumbbell_bench_press')
  const failures=await page.evaluate(async(catalog)=>{
   const {exerciseInstructions,t}=await import('/js/i18n.js')
   return catalog.filter(ex=>{
    const notes=exerciseInstructions(ex)
    return notes.includes(t('exercises.dumbbell_weight_entry'))!==ex.equipment_required.some(c=>c.startsWith('dumbbell'))
   }).map(ex=>ex.id)
  },catalog)
  expect(failures).toEqual([])
  for(const id of ['one_arm_dumbbell_row','dumbbell_bench_press']){
   await page.goto('/#/exercises/'+id)
   await expect(page.locator('.instruction-list li').last()).toHaveText(L('exercises.dumbbell_weight_entry'))
  }
  await page.goto('/#/exercises/barbell_bench_press_medium_grip')
  await expect(page.getByText(L('exercises.dumbbell_weight_entry'),{exact:true})).toHaveCount(0)
 })
