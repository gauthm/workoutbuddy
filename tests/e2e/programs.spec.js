import {test,expect} from './fixtures.js'
import {L,get,homeGym,planned} from './helpers.js'

test('questionnaire → aperçu → création → activation, puis persistance après rechargement',async({page,request})=>{
 await homeGym(request)
 await page.goto('/#/programs')
 await page.getByRole('button',{name:L('programs.new'),exact:true}).click()
 const next=()=>page.getByRole('button',{name:L('planner.next'),exact:true}).click()
 await next();await next()
 await page.getByLabel('Mercredi',{exact:true}).uncheck()
 await page.getByLabel('Vendredi',{exact:true}).uncheck()
 await page.getByLabel('Jeudi',{exact:true}).check()
 await next()
 await page.locator('input[name="duration"][value="20"]').check()
 await next()
 await page.locator('#program-weight').fill('75');await page.locator('#program-height').fill('175')
 await next();await next();await next()
 await page.getByText(L('planner.unlimited'),{exact:true}).click()
 await next()
 await expect(page.locator('.program-wizard__review')).toBeVisible()
 await page.getByRole('button',{name:L('planner.create'),exact:true}).click()
 await page.waitForURL(/#\/programs\/\d+$/)
 await page.getByRole('button',{name:L('programs.activate'),exact:true}).click()
 await expect(page.getByRole('button',{name:L('programs.start_session'),exact:true})).toBeVisible()
 await page.reload()
 const list=(await get(request,'/programs')).programs
 expect(list).toHaveLength(1)
 const p=await get(request,`/programs/${list[0].id}`)
 expect(p.is_active).toBe(true);expect(p.duration_weeks).toBeNull()
 expect(p.plan.parameters.training_days).toEqual([0,3])
 expect(p.plan.parameters.session_duration_min).toBe(20)
 expect((await get(request,'/sessions?active_program=1')).sessions.length).toBeGreaterThan(0)
})

test('modifier les jours exige la fréquence initiale et conserve objectif, exercices et durée de séance',async({page,request})=>{
 const p=await planned(request)
 await page.goto(`/#/programs/${p.id}`)
 await page.getByRole('button',{name:L('programs.edit_program'),exact:true}).click()
 const dialog=page.getByRole('dialog')
 await dialog.getByLabel('Lundi',{exact:true}).uncheck()
 await expect(dialog.getByRole('button',{name:L('common.save'),exact:true})).toBeDisabled()
 expect((await get(request,`/programs/${p.id}`)).plan.parameters).toEqual(p.plan.parameters)
 await dialog.getByLabel('Mardi',{exact:true}).check()
 await dialog.locator('#program-duration-weeks').fill('12')
 await dialog.getByRole('button',{name:L('common.save'),exact:true}).click()
 await expect(dialog).toHaveCount(0)
 await page.reload()
 const after=await get(request,`/programs/${p.id}`)
 expect(after.plan.parameters).toEqual({...p.plan.parameters,training_days:[1,3],duration_weeks:12})
 expect(after.templates.map(t=>t.exercises)).toEqual(p.templates.map(t=>t.exercises))
})

test('remplacer un exercice par une alternative réelle conserve le changement après rechargement',async({page,request})=>{
 const p=await planned(request)
 const slot=p.templates[0].exercises[0]
 await page.goto(`/#/programs/${p.id}`)
 await page.locator('.program-replace-btn').first().click()
 const dialog=page.getByRole('dialog'),choice=dialog.locator('input[name="replacement-exercise"]').first()
 await expect(choice).toBeVisible()
 const replacement=await choice.getAttribute('value')
 await choice.check()
 await dialog.getByRole('button',{name:L('programs.replace'),exact:true}).click()
 await expect(dialog).toHaveCount(0)
 await page.reload()
 const after=await get(request,`/programs/${p.id}`)
 expect(after.templates[0].exercises[0].exercise_id).toBe(replacement)
 expect(replacement).not.toBe(slot.exercise_id)
})
