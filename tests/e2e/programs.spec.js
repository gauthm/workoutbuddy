 await next()
 const full=await(await longer).json()
 expect(full.templates).toHaveLength(2)
 expect(full.priority_coverage.every(p=>p.status==='direct')).toBe(true)
 expect(full.warnings.some(w=>w.code.startsWith('priority_'))).toBe(false)
